-- ---------- tables (created only if missing) ----------
create table if not exists users (
  id uuid primary key references auth.users(id), email text not null, created_at timestamp default now());

create table if not exists receipts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id),
  source text, raw_text text, image_url text,
  created_at timestamp default now());

create table if not exists expenses (
  id uuid primary key default gen_random_uuid(),
  receipt_id uuid references receipts(id),
  user_id uuid references users(id),
  merchant text, date date, total float, currency text default 'INR',
  category text, payment_method text, line_items jsonb default '[]',
  created_at timestamp default now());

create table if not exists anomalies (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id),
  expense_id uuid references expenses(id),
  type text, description text,
  flagged_at timestamp default now(), resolved boolean default false);

create table if not exists insights (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id),
  month text, predictions jsonb default '{}', inflation_flags jsonb default '[]',
  summary_text text, generated_at timestamp default now());

