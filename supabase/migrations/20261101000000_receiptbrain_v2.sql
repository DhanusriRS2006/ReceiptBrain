-- semantic search: closest expenses to a query vector (<=> = cosine distance)
create or replace function search_expenses(query_embedding vector(384), match_count int default 10)
returns table (id uuid, merchant text, date date, total float, category text,
               payment_method text, similarity float)
language sql stable as $$
  select e.id, e.merchant, e.date, e.total, e.category, e.payment_method,
         1 - (e.embedding <=> query_embedding) as similarity
  from expenses e
  where e.embedding is not null
  order by e.embedding <=> query_embedding
  limit match_count;
$$;

-- duplicate charges: look-alike expense, within p_days, amount within 1% (min Rs.1)
create or replace function find_duplicate_candidates(p_expense_id uuid, p_days int default 7,
                                                      p_threshold float default 0.9)
returns table (id uuid, merchant text, total float, date date, similarity float)
language sql stable as $$
  select e2.id, e2.merchant, e2.total, e2.date, 1 - (e2.embedding <=> e1.embedding)
  from expenses e1
  join expenses e2 on e2.id <> e1.id
  where e1.id = p_expense_id
    and e1.embedding is not null and e2.embedding is not null
    and abs(e2.date - e1.date) <= p_days
    and abs(e2.total - e1.total) <= greatest(1, e1.total * 0.01)
    and 1 - (e2.embedding <=> e1.embedding) >= p_threshold
  order by e2.embedding <=> e1.embedding
  limit 5;
$$;
